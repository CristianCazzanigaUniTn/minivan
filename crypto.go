// DeriveKey turns a password into a 256-bit file key
//
// CBOMs: no (Argon2 appears only as a library in cdxgen, not as an asset with parameters)
// FIXES: 
// 	- Argon2id stays, it is PQ. Parameters changed according to the configuration recommended by RFC 9106.
func DeriveKey(password string, salt []byte) []byte {
	return argon2.IDKey([]byte(password), salt, 3, 64*1024, 4, keyLen)
}



// nonceLen is 16 (not 12): nonce 16 + padded data + tag 16 stays a multiple of 16 (test constraint).
const nonceLen = 16

// newGCM builds AES-256-GCM with a 16-byte nonce.
//
// CBOMs: no
// FIXES:
// 	- new function. Accepts only keyLen (32 bytes): AES-256 only, no short keys.
func newGCM(key []byte) (cipher.AEAD, error) {
	if len(key) != keyLen {
		return nil, errors.New("invalid key length")
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	return cipher.NewGCMWithNonceSize(block, nonceLen)
}

// Encrypt produces nonce || AES-256-GCM(PKCS#7(plain)) (tag at the end)
//
// CBOMs: yes (AES at line 86: the CBOM says 128 but the key is 256 bits) / no (ECB mode)
// FIXES:
// 	- before, each block was encrypted on its own (ECB), without authentication and not matching the comment "equivalent to AES-GCM".
// 	  Now real AES-256-GCM with a random 16-byte nonce 
// NOTE: the nonce is 16 and not 12 to keep the ciphertext a multiple of 16, required by TestEncryptDecryptRoundTrip).
func Encrypt(key, plain []byte) ([]byte, error) {
	gcm, err := newGCM(key)
	if err != nil {
		return nil, err
	}
	pad := aes.BlockSize - len(plain)%aes.BlockSize
	padded := append(append([]byte{}, plain...), bytes.Repeat([]byte{byte(pad)}, pad)...)
	defer clear(padded)
	out := make([]byte, nonceLen, nonceLen+len(padded)+gcm.Overhead())
	if _, err = rand.Read(out); err != nil {
		return nil, err
	}
	return gcm.Seal(out, out[:nonceLen], padded, nil), nil
}

// CBOMs: yes (AES) / no (ECB, no authentication)
// FIXES: p
// 	- before, decryption checked nothing except the padding. Now gcm.Open verifies the tag.
func Decrypt(key, data []byte) ([]byte, error) {
	gcm, err := newGCM(key)
	if err != nil {
		return nil, err
	}
	if len(data) < nonceLen+aes.BlockSize+gcm.Overhead() || len(data)%aes.BlockSize != 0 {
		return nil, errors.New("invalid ciphertext length")
	}
	out, err := gcm.Open(nil, data[:nonceLen], data[nonceLen:], nil)
	if err != nil {
		return nil, errors.New("authentication failed")
	}
	pad := int(out[len(out)-1])
	if pad == 0 || pad > aes.BlockSize || !bytes.HasSuffix(out, bytes.Repeat([]byte{byte(pad)}, pad)) {
		clear(out)
		return nil, errors.New("invalid padding")
	}
	return out[:len(out)-pad], nil
}

// Checksum is the integrity value stored next to encrypted data
//
// CBOMs: yes (MD5 at line 124)
// FIXES: 
// 	- MD5 is broken and no longer used: the function returns SHA-256 (FIPS 180-4).
// WARNING: TestChecksum, if it still hardcodes the MD5 values, now FAILS: it must be updated with the SHA-256 values.
func Checksum(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

// kekFromSecret turns the ML-KEM shared secret into the key that wraps the file key
//
// CBOMs: no
// FIXES: 
// 	- Added HKDF-SHA-256 with the label "vaultshare/key-wrap/v1".
// 	- sharedKey/ECDH replaced by ML-KEM encapsulation.
func kekFromSecret(secret []byte) ([]byte, error) {
	return hkdf.Key(sha256.New, secret, nil, "vaultshare/key-wrap/v1", keyLen)
}

// WrapKey encrypts a file key for the owner of recipientECC; ephemeral (the KEM ciphertext) must travel with it
//
// CBOMs: no 
// FIXES: 
// 	- ECDH replaced with ML-KEM encapsulation: Encapsulate generates a random shared secret
// 	  and its "ciphertext" (1568 bytes with ML-KEM-1024).
func WrapKey(recipientECC, fileKey []byte) (ephemeral, wrapped []byte, err error) {
	ek, err := mlkem.NewEncapsulationKey1024(recipientECC)
	if err != nil {
		return nil, nil, err
	}
	secret, kemCT := ek.Encapsulate()
	defer clear(secret)
	kek, err := kekFromSecret(secret)
	if err != nil {
		return nil, nil, err
	}
	defer clear(kek)
	wrapped, err = Encrypt(kek, fileKey)
	if err != nil {
		return nil, nil, err
	}
	return kemCT, wrapped, nil
}

// CBOMs: no 
// FIXES: 
// 	- replaced ECDH + SHA-256 with ML-KEM Decapsulate + HKDF. 
func (k *Keys) UnwrapKey(ephemeral, wrapped []byte) ([]byte, error) {
	secret, err := k.kemKey.Decapsulate(ephemeral)
	if err != nil {
		return nil, err
	}
	defer clear(secret)
	kek, err := kekFromSecret(secret)
	if err != nil {
		return nil, err
	}
	defer clear(kek)
	key, err := Decrypt(kek, wrapped)
	if err == nil && len(key) != keyLen {
		clear(key)
		key, err = nil, errors.New("unexpected key length")
	}
	return key, err
}

// CBOMs: yes (RSA-2048 and MD5, Hyperion lines 166 and 37)
// FIXES: 
// 	- MD5 digest signed with RSA-2048 PKCS#1 (not post-quantum) (collision problem). 
//	  replaced with an ML-DSA signature (FIPS 204) directly on the message,
// 	  ML-DSA uses its own hashing internally, so MD5 disappears from the signature.
func (k *Keys) Sign(data []byte) ([]byte, error) {
	sig := make([]byte, mldsa87.SignatureSize)
	if err := mldsa87.SignTo(k.sigKey, data, []byte("vaultshare/package-signature/v1"), true, sig); err != nil {
		return nil, err
	}
	return sig, nil
}

// CBOMs: yes (RSA-2048, MD5 and ParsePKCS1PublicKey at lines 171 and 175)
// FIXES: 
// - Verification with the ML-DSA public key.
func Verify(rsaPublicDER, data, sig []byte) error {
	if len(rsaPublicDER) != mldsa87.PublicKeySize {
		return errors.New("invalid ML-DSA public key length")
	}
	var pub mldsa87.PublicKey
	pub.Unpack((*[mldsa87.PublicKeySize]byte)(rsaPublicDER))
	if !mldsa87.Verify(&pub, data, []byte("vaultshare/package-signature/v1"), sig) {
		return errors.New("signature verification failed")
	}
	return nil
}