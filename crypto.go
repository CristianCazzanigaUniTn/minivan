const keyLen = 32

// Keys contains a user's key material
//
// CBOMs: yes (RSA-2048, PKCS#1 keys) / no (ECDH P-256, absent from both CBOMs)
// FIXES:
// 	- rsa.PrivateKey -> mldsa.PrivateKey (ML-DSA, FIPS 204) for signing.
//  - ecdh.PrivateKey P-256 -> mlkem.DecapsulationKey (ML-KEM, FIPS 203) for key exchange.
// 	RSA and ECDH are broken by Shor. 
// We deliberately left the names RSAPrivate/ECCPrivate unchanged so as not to cause problems with the tests.
// ML-DSA-87 (NIST category 5), ML-KEM-1024 (NIST category 5), in line with AES-256 (category 5).
type Keys struct {
	RSAPrivate string // PEM (seed ML-DSA-87)
	ECCPrivate []byte // raw seed ML-KEM-1024
	sigKey     *mldsa87.PrivateKey
	sigPub     *mldsa87.PublicKey
	kemKey     *mlkem.DecapsulationKey1024
}

// CBOMs: yes (RSA-2048 at line 37) / no (ECDH P-256, weak PRNG)
// FIXES: 
// 	- Removed fastReader (math/rand seeded with time.Now().Unix(), predictable): 
// 	  keys are now generated by the library with the system CSPRNG. 
// 	- RSA-2048 (not PQ, signing), replaced with ML-DSA;
// 	- ECDH P-256 (not PQ, key exchange), replaced with ML-KEM.
// ML-DSA-65 -> ML-DSA-87 (FIPS 204, category 5) and ML-KEM-768 -> ML-KEM-1024 (FIPS 203, category 5).
func NewKeys() (Keys, error) {
	var seed [mldsa87.SeedSize]byte // il seed da 32 byte e' l'unico dato da salvare: da qui CIRCL ricostruisce la chiave
	if _, err := rand.Read(seed[:]); err != nil {
		return Keys{}, err
	}
	sigPub, sigKey := mldsa87.NewKeyFromSeed(&seed)
	kemKey, err := mlkem.GenerateKey1024()
	if err != nil {
		return Keys{}, err
	}
	seedPEM := pem.EncodeToMemory(&pem.Block{Type: "ML-DSA-87 PRIVATE KEY", Bytes: seed[:]})
	clear(seed[:]) // [F17] il seed ormai e' nel PEM: si azzera la copia locale
	return Keys{RSAPrivate: string(seedPEM), ECCPrivate: kemKey.Bytes(), sigKey: sigKey, sigPub: sigPub, kemKey: kemKey}, nil
}

// Load parses the stored private keys
//
// CBOMs: yes (PKCS#1, ParsePKCS1PrivateKey at line 55) / no (ECDH, NewPrivateKey at line 58)
// FIXES:
// 	- PKCS#1 and P-256 parsing becomes reconstruction from the ML-DSA and ML-KEM seeds.
// 	- The PEM block type is also checked, so an old file with an RSA key is rejected with a clear
// 	  error instead of being misinterpreted. Empty input, non-PEM input or a wrong-length seed returns an error.
//  - Reconstruction from ML-DSA-87 / ML-KEM-1024. 
func (k *Keys) Load() (err error) {
	block, _ := pem.Decode([]byte(k.RSAPrivate))
	if block == nil || block.Type != "ML-DSA-87 PRIVATE KEY" {
		return errors.New("no ML-DSA key found")
	}
	if len(block.Bytes) != mldsa87.SeedSize {
		return errors.New("invalid ML-DSA seed length")
	}
	k.sigPub, k.sigKey = mldsa87.NewKeyFromSeed((*[mldsa87.SeedSize]byte)(block.Bytes))
	k.kemKey, err = mlkem.NewDecapsulationKey1024(k.ECCPrivate)
	return err
}

// PublicKeys returns the public halves: the ML-DSA-87 key for signatures, the ML-KEM-1024 key for key transport
//
// CBOMs: yes (MarshalPKCS1PublicKey at line 64)
// FIXES: PKCS#1 public keys (RSA) and the P-256 point replaced with ML-DSA and ML-KEM public keys.
func (k *Keys) PublicKeys() (rsaDER, eccRaw []byte) {
	var pub [mldsa87.PublicKeySize]byte
	k.sigPub.Pack(&pub)
	return pub[:], k.kemKey.EncapsulationKey().Bytes()
}


// Fingerprint is a short hash of public key material, for people to compare
//
// CBOMs: yes (SHA-256 at line 69, flagged as correct)
// FIXES: 
// 	- SHA-256 is secure, only the ambiguous concatenation bytes.Join(parts, nil) is fixed: now
// 	  each part is preceded by its length (4 bytes), so (a,b) and (ab,"") do not give the same fingerprint.
// 	  The truncation to 12 bytes (24 hex characters) is kept because TestFingerprint requires it.
func Fingerprint(parts ...[]byte) string {
	h := sha256.New()
	for _, p := range parts {
		var n [4]byte
		binary.BigEndian.PutUint32(n[:], uint32(len(p)))
		h.Write(n[:])
		h.Write(p)
	}
	return hex.EncodeToString(h.Sum(nil)[:12])
}

